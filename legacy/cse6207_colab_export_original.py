import torch, os

def save_ckpt(path, model, optimizer=None, epoch=0, extra=None):
    payload = {"model": model.state_dict(), "epoch": epoch}
    if optimizer is not None:
        payload["optimizer"] = optimizer.state_dict()
    if extra:
        payload["extra"] = extra
    torch.save(payload, path)
    print(f"saved -> {path} (epoch {epoch})")

def load_ckpt(path, model, optimizer=None, map_location=None):
    if not os.path.exists(path):
        print("no checkpoint at", path, "-> starting fresh")
        return 0
    ck = torch.load(path, map_location=map_location)
    model.load_state_dict(ck["model"])
    if optimizer is not None and "optimizer" in ck:
        optimizer.load_state_dict(ck["optimizer"])
    print(f"loaded <- {path} (epoch {ck.get('epoch',0)})")
    return ck.get("epoch", 0)

