import torch.nn as nn

class ConvAE(nn.Module):
    """Lightweight conv autoencoder. `width` scales capacity.
       residual=True makes it predict the clean image as (input + correction),
       which strongly protects clean images from being blurred (Paper B failure mode)."""
    def __init__(self, width=16, residual=True):
        super().__init__()
        w = width
        self.residual = residual
        self.enc = nn.Sequential(
            nn.Conv2d(3, w, 3, 2, 1), nn.ReLU(inplace=True),      # 64->32
            nn.Conv2d(w, w*2, 3, 2, 1), nn.ReLU(inplace=True),    # 32->16
        )
        self.dec = nn.Sequential(
            nn.ConvTranspose2d(w*2, w, 4, 2, 1), nn.ReLU(inplace=True),  # 16->32
            nn.ConvTranspose2d(w, 3, 4, 2, 1),                          # 32->64
        )
    def forward(self, x):
        out = self.dec(self.enc(x))
        out = x + out if self.residual else out
        return torch.clamp(out, 0.0, 1.0)

