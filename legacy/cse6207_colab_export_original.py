class KermanyDS(Dataset):
    """Full-res grayscale X-ray -> 64x64 RGB [0,1], matching the training pipeline.
       corruption=None means clean; otherwise apply (name, severity)."""
    def __init__(self, items, corruption=None, severity=None):
        self.items, self.c, self.s = items, corruption, severity
    def __len__(self): return len(self.items)
    def __getitem__(self, i):
        path, lab = self.items[i]
        img = Image.open(path).convert("RGB").resize((64, 64))   # grayscale->RGB, match size
        if self.c is not None:
            from PIL import Image as PILImage
            arr = corrupt(img, self.c, self.s)                   # uint8
            img = PILImage.fromarray(arr)
        t = torch.from_numpy(np.array(img)).float().permute(2,0,1)/255.0
        return t, lab

